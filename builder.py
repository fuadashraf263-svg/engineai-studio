#!/usr/bin/env python3
"""
builder.py -- generate engineering ARTEFACTS, and verify them by running.

Your uploaded labs are PSpice circuits and MATLAB scripts. That is the
"build the thing they asked for" tier -- and unlike a prose answer, an
artefact can be CHECKED by executing it. A netlist either solves to the
node voltages or it does not. A MATLAB script either runs or it errors.

So this file does two things that most "AI writes code" tools skip:

  1. It SOLVES the circuit itself, with nodal analysis in numpy, and
     reports the node voltages -- so the answer is [SOLVED], not
     [UNVERIFIED]. For the uploaded Example 1 it reproduces the PSpice
     node voltages (232 V, 136 V, 132 V) from the netlist alone.

  2. For MATLAB, it emits code AND runs it in Octave if Octave is present,
     reporting the actual output. Generated code that does not execute is
     flagged, not handed over.

This is the same rule as every solver domain: never give an answer you
have not checked against the thing it claims to do.

Run:  python builder.py --selftest
      python builder.py circuit example1.json
      python builder.py matlab "plot cos(n) for n=0:10"
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np


# ==========================================================================
#  CIRCUITS -- generate a netlist AND solve it
# ==========================================================================

def solve_resistive_circuit(spec: dict) -> dict:
    """Modified Nodal Analysis for R, I, V and VCCS (G) elements.

    spec = {
      "nodes": <highest node number; 0 is ground>,
      "R": [["R1", n1, n2, ohms], ...],
      "I": [["I1", n_from, n_to, amps], ...],   # current n_from -> n_to
      "V": [["V1", n_plus, n_minus, volts], ...],
      "G": [["G1", n_out_p, n_out_m, n_ctrl_p, n_ctrl_m, gain_S], ...]
    }
    Returns node voltages with node 0 = 0 V (reference).
    """
    N = spec["nodes"]
    vsrc = spec.get("V", [])
    m = len(vsrc)
    A = np.zeros((N + m, N + m))
    z = np.zeros(N + m)

    def gstamp(a, b, val):
        for i, s1 in ((a, 1), (b, -1)):
            if i == 0:
                continue
            for j, s2 in ((a, 1), (b, -1)):
                if j == 0:
                    continue
                A[i - 1, j - 1] += val * s1 * s2

    for _, a, b, r in spec.get("R", []):
        gstamp(a, b, 1.0 / r)

    for _, a, b, amps in spec.get("I", []):   # current from a to b
        if a:
            z[a - 1] -= amps
        if b:
            z[b - 1] += amps

    # VCCS: current gain*(Vcp - Vcm) flows from out_p to out_m
    for g in spec.get("G", []):
        _, op, om, cp, cm, gain = g
        for outn, so in ((op, 1), (om, -1)):
            if outn == 0:
                continue
            for ctrln, sc in ((cp, 1), (cm, -1)):
                if ctrln == 0:
                    continue
                A[outn - 1, ctrln - 1] += gain * so * sc

    for k, (_, npl, nmi, volts) in enumerate(vsrc):
        row = N + k
        if npl:
            A[row, npl - 1] += 1
            A[npl - 1, row] += 1
        if nmi:
            A[row, nmi - 1] -= 1
            A[nmi - 1, row] -= 1
        z[row] = volts

    x = np.linalg.solve(A, z)
    volts = {0: 0.0}
    for i in range(1, N + 1):
        volts[i] = float(x[i - 1])
    return {"node_voltages": volts,
            "source_currents": {vsrc[k][0]: float(x[N + k])
                                for k in range(m)},
            "provenance": "SOLVED (nodal analysis)"}


def emit_spice(spec: dict, title="EngineAI circuit") -> str:
    lines = [f"* {title}", "* generated by EngineAI builder"]
    for nm, a, b, r in spec.get("R", []):
        lines.append(f"R{nm.lstrip('R')} {a} {b} {r}")
    for nm, a, b, i in spec.get("I", []):
        lines.append(f"I{nm.lstrip('I')} {a} {b} DC {i}")
    for nm, a, b, v in spec.get("V", []):
        lines.append(f"V{nm.lstrip('V')} {a} {b} DC {v}")
    for g in spec.get("G", []):
        nm, op, om, cp, cm, gain = g
        lines.append(f"G{nm.lstrip('G')} {op} {om} {cp} {cm} {gain}")
    lines += [".op", ".end"]
    return "\n".join(lines)


def build_circuit(spec: dict, out: Path | None = None) -> dict:
    sol = solve_resistive_circuit(spec)
    net = emit_spice(spec)
    if out:
        out.write_text(net)
    return {"netlist": net, "solution": sol,
            "netlist_path": str(out) if out else None}


# ==========================================================================
#  MATLAB / OCTAVE -- generate a script AND run it
# ==========================================================================

def run_octave(code: str) -> dict:
    oct_bin = shutil.which("octave") or shutil.which("octave-cli")
    if not oct_bin:
        return {"ran": False, "reason": "octave not installed "
                "(sudo apt install -y octave); script emitted but UNVERIFIED"}
    with tempfile.NamedTemporaryFile("w", suffix=".m", delete=False) as f:
        f.write(code)
        path = f.name
    try:
        r = subprocess.run([oct_bin, "--no-gui", "-q", path],
                           capture_output=True, text=True, timeout=60)
        return {"ran": True, "returncode": r.returncode,
                "stdout": r.stdout[-2000:], "stderr": r.stderr[-500:],
                "ok": r.returncode == 0}
    finally:
        Path(path).unlink(missing_ok=True)


def build_matlab(description: str, code: str | None = None,
                 out: Path | None = None) -> dict:
    """Emit a MATLAB/Octave script (from provided code or a tiny template)
    and RUN it to prove it works."""
    if code is None:
        code = ("% EngineAI generated\n"
                "n = 0:10;\n"
                "y = cos(n);\n"
                "disp(y);\n")
    res = run_octave(code)
    res["provenance"] = ("SOLVED (executed in Octave)" if res.get("ok")
                         else "GENERATED (not executed)")
    if out:
        out.write_text(code)
        res["path"] = str(out)
    res["code"] = code
    return res


# ==========================================================================
#  SELF-TEST
# ==========================================================================

def selftest() -> int:
    G, R, O = "\033[32m", "\033[31m", "\033[0m"
    fails = 0

    def chk(label, cond, detail=""):
        nonlocal fails
        fails += (not cond)
        print(f"  {(G+'PASS'+O) if cond else (R+'FAIL'+O)}  {label:46s} "
              f"{detail}")

    print("\n== BUILDER SELF-TEST " + "=" * 45)

    # ---- a simple divider with a known answer ----------------------------
    # 10 V across two 1k resistors -> midpoint at 5 V.
    div = {"nodes": 2, "V": [["V1", 1, 0, 10.0]],
           "R": [["R1", 1, 2, 1000.0], ["R2", 2, 0, 1000.0]]}
    s = solve_resistive_circuit(div)
    chk("voltage divider midpoint = 5 V", abs(s["node_voltages"][2] - 5.0)
        < 1e-9, f"{s['node_voltages'][2]:.4f} V")

    # ---- the UPLOADED Example 1, from its netlist ------------------------
    # R_R1 V1 V3 500 ; R_R2 V1 V2 120 ; R_R3 0 V3 200 ; R_R4 0 V2 400 ;
    # V_V1 V2 V3 4 ; I_I1 0 V1 DC 1A     (nodes: V1=1, V2=2, V3=3)
    ex1 = {"nodes": 3,
           "R": [["R1", 1, 3, 500.0], ["R2", 1, 2, 120.0],
                 ["R3", 0, 3, 200.0], ["R4", 0, 2, 400.0]],
           "V": [["V1", 2, 3, 4.0]],
           "I": [["I1", 0, 1, 1.0]]}
    s = solve_resistive_circuit(ex1)
    v = s["node_voltages"]
    print(f"       Example 1 node voltages: V1={v[1]:.1f} V2={v[2]:.1f} "
          f"V3={v[3]:.1f}")
    # PSpice printed 232.0 / 136.0 / 132.0 on the schematic
    chk("Example 1 V1 = 232 V (matches PSpice)", abs(v[1] - 232.0) < 0.5,
        f"{v[1]:.2f}")
    chk("Example 1 V2 = 136 V (matches PSpice)", abs(v[2] - 136.0) < 0.5,
        f"{v[2]:.2f}")
    chk("Example 1 V3 = 132 V (matches PSpice)", abs(v[3] - 132.0) < 0.5,
        f"{v[3]:.2f}")

    # ---- netlist round-trips to text -------------------------------------
    net = emit_spice(ex1)
    chk("netlist contains all 4 resistors",
        all(f"R{n}" in net for n in (1, 2, 3, 4)))
    chk("netlist has .op and .end", ".op" in net and ".end" in net)

    # ---- MATLAB generation + execution -----------------------------------
    r = build_matlab("cos table", "n=0:10; y=cos(n); printf('%.4f ', y(1)); "
                     "printf('%.4f', y(3));\n")
    if r.get("ran"):
        chk("generated MATLAB executes in Octave", r.get("ok"),
            r.get("stderr", "")[:40])
        chk("Octave output starts 1.0000 (cos 0)",
            r["stdout"].strip().startswith("1.0000"),
            r["stdout"][:30])
    else:
        print(f"  {R}SKIP{O}  Octave not installed: {r['reason'][:50]}")

    print(f"\n  {'ALL CHECKS PASS' if not fails else str(fails)+' FAILURE(S)'}")
    return 1 if fails else 0


def main() -> int:
    a = sys.argv[1:]
    if not a or a[0] == "--help":
        print(__doc__.split("Run:")[-1])
        return 0
    if a[0] == "--selftest":
        return selftest()
    if a[0] == "circuit" and len(a) > 1:
        spec = json.loads(Path(a[1]).read_text())
        r = build_circuit(spec, Path("circuit.cir"))
        print(r["netlist"])
        print("\n  node voltages:", r["solution"]["node_voltages"])
        return 0
    if a[0] == "matlab":
        r = build_matlab(" ".join(a[1:]))
        print(r["code"])
        print("  provenance:", r["provenance"])
        if r.get("ran"):
            print("  output:", r["stdout"][:200])
        return 0
    print("commands: circuit <spec.json> | matlab <desc> | --selftest")
    return 1


if __name__ == "__main__":
    sys.exit(main())
